#!/usr/bin/env node
/**
 * Copy the contract ABIs out of the Foundry build into `lib/contracts/abis/`.
 *
 * ## Why generate rather than hand-write
 *
 * A hand-written ABI is a second source of truth for a function signature, and the way
 * it fails is quiet: `viem` encodes against whatever the app believes, the chain decodes
 * against what was deployed, and a renamed argument or a changed type produces a revert
 * with no useful message. The contracts repo already emits the real thing, so the app
 * should read it.
 *
 * ## Why `as const` matters
 *
 * `viem` and `wagmi` derive their types *from the ABI value*, not from a schema. Without
 * `as const` the array widens to `string[]` and every call loses its argument and return
 * types — the client still compiles and is no longer checked, which is the worst of both
 * worlds. That is the whole reason this writes TypeScript instead of JSON.
 *
 * Usage, from the app root:
 *
 *   node scripts/sync-abis.mjs                   # expects ../agent-circle-evm
 *   EVM_REPO=/path/to/agent-circle-evm node scripts/sync-abis.mjs
 */
import { readFile, writeFile, mkdir, access } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const appRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const evmRepo = process.env.EVM_REPO ?? join(appRoot, "..", "agent-circle-evm");
const outDir = join(appRoot, "lib", "contracts", "abis");

/** `[solidity file, contract name]`. Only what the app actually calls. */
const CONTRACTS = [
  ["AgentRegistry.sol", "AgentRegistry"],
  ["HLAgentVault.sol", "HLAgentVault"],
  ["HLAgentVaultFactory.sol", "HLAgentVaultFactory"],
  ["HLMarketWhitelist.sol", "HLMarketWhitelist"],
];

const BANNER = `// Generated by scripts/sync-abis.mjs. Do not edit.
//
// Source of truth is the Foundry build in agent-circle-evm. Re-run \`npm run sync-abis\`
// after any change to a contract's interface; CI fails if this file is stale.
`;

async function exists(path) {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

async function main() {
  const check = process.argv.includes("--check");

  if (!(await exists(join(evmRepo, "out")))) {
    console.error(
      `No Foundry build at ${join(evmRepo, "out")}.\n` +
        `Run \`forge build\` in the contracts repo first, or set EVM_REPO.`
    );
    process.exit(1);
  }

  await mkdir(outDir, { recursive: true });
  let stale = [];

  for (const [file, name] of CONTRACTS) {
    const artifactPath = join(evmRepo, "out", file, `${name}.json`);
    if (!(await exists(artifactPath))) {
      console.error(`Missing artifact: ${artifactPath}`);
      process.exit(1);
    }

    const artifact = JSON.parse(await readFile(artifactPath, "utf8"));

    // Events and errors are kept, not just functions. `viem` decodes revert reasons from
    // the error entries, which is the difference between "PositionCapExceeded" and an
    // unreadable hex blob in front of a user.
    const abi = artifact.abi;
    const target = join(outDir, `${name}.ts`);
    const body = `${BANNER}
export const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;
`;

    if (check) {
      const current = (await exists(target)) ? await readFile(target, "utf8") : "";
      if (current !== body) stale.push(name);
    } else {
      await writeFile(target, body);
      console.log(`  ${name}  (${abi.length} entries)`);
    }
  }

  const indexBody = `${BANNER}
${CONTRACTS.map(([, n]) => `export { ${n}Abi } from "./${n}";`).join("\n")}
`;
  const indexPath = join(outDir, "index.ts");

  if (check) {
    const current = (await exists(indexPath)) ? await readFile(indexPath, "utf8") : "";
    if (current !== indexBody) stale.push("index");

    if (stale.length) {
      console.error(
        `ABIs are stale: ${stale.join(", ")}.\n` +
          `Run \`npm run sync-abis\` and commit the result.`
      );
      process.exit(1);
    }
    console.log("✓ ABIs match the contracts build");
    return;
  }

  await writeFile(indexPath, indexBody);
  console.log(`Wrote ${CONTRACTS.length} ABIs to lib/contracts/abis/`);
}

await main();
